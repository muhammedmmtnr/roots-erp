CREATE TABLE IF NOT EXISTS public.products (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  sku text NOT NULL UNIQUE,
  barcode text UNIQUE,
  category text NOT NULL DEFAULT 'General',
  unit text NOT NULL DEFAULT 'pcs',
  price numeric(14, 2) NOT NULL DEFAULT 0 CHECK (price >= 0),
  cost numeric(14, 2) NOT NULL DEFAULT 0 CHECK (cost >= 0),
  stock numeric(14, 3) NOT NULL DEFAULT 0 CHECK (stock >= 0),
  low_stock numeric(14, 3) NOT NULL DEFAULT 5 CHECK (low_stock >= 0),
  tax_rate numeric(6, 3) NOT NULL DEFAULT 18 CHECK (tax_rate >= 0),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.contacts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  type text NOT NULL CHECK (type IN ('customer', 'supplier', 'both')),
  phone text NOT NULL DEFAULT '',
  email text NOT NULL DEFAULT '',
  gstin text NOT NULL DEFAULT '',
  address text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.transactions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  number text NOT NULL UNIQUE,
  type text NOT NULL CHECK (type IN ('retail', 'wholesale', 'purchase')),
  contact_id bigint REFERENCES public.contacts(id) ON DELETE SET NULL,
  contact_name text NOT NULL,
  subtotal numeric(14, 2) NOT NULL CHECK (subtotal >= 0),
  tax numeric(14, 2) NOT NULL CHECK (tax >= 0),
  total numeric(14, 2) NOT NULL CHECK (total >= 0),
  payment_method text NOT NULL DEFAULT 'Cash',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.transaction_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transaction_id bigint NOT NULL REFERENCES public.transactions(id) ON DELETE CASCADE,
  product_id bigint REFERENCES public.products(id) ON DELETE SET NULL,
  product_name text NOT NULL,
  quantity numeric(14, 3) NOT NULL CHECK (quantity > 0),
  unit_price numeric(14, 2) NOT NULL CHECK (unit_price >= 0),
  tax_rate numeric(6, 3) NOT NULL CHECK (tax_rate >= 0),
  line_total numeric(14, 2) NOT NULL CHECK (line_total >= 0)
);

CREATE TABLE IF NOT EXISTS public.settings (
  key text PRIMARY KEY,
  value text NOT NULL
);

CREATE INDEX IF NOT EXISTS transactions_created_at_idx ON public.transactions (created_at DESC);
CREATE INDEX IF NOT EXISTS transactions_type_created_at_idx ON public.transactions (type, created_at DESC);
CREATE INDEX IF NOT EXISTS transaction_items_transaction_id_idx ON public.transaction_items (transaction_id);
CREATE INDEX IF NOT EXISTS products_name_idx ON public.products (name);
CREATE INDEX IF NOT EXISTS contacts_name_idx ON public.contacts (name);

ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.contacts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.transactions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.transaction_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.settings ENABLE ROW LEVEL SECURITY;

GRANT ALL ON public.products, public.contacts, public.transactions, public.transaction_items, public.settings TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;

CREATE OR REPLACE FUNCTION public.create_erp_transaction(
  p_number text,
  p_type text,
  p_contact_id bigint,
  p_contact_name text,
  p_payment_method text,
  p_items jsonb
)
RETURNS public.transactions
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_item jsonb;
  v_product public.products%ROWTYPE;
  v_contact public.contacts%ROWTYPE;
  v_quantity numeric(14, 3);
  v_unit_price numeric(14, 2);
  v_net numeric(14, 2);
  v_line_tax numeric(14, 2);
  v_subtotal numeric(14, 2) := 0;
  v_tax numeric(14, 2) := 0;
  v_name text;
  v_transaction public.transactions%ROWTYPE;
  v_product_id bigint;
BEGIN
  IF p_type NOT IN ('retail', 'wholesale', 'purchase') THEN
    RAISE EXCEPTION 'Invalid transaction type';
  END IF;
  IF jsonb_typeof(p_items) <> 'array' OR jsonb_array_length(p_items) < 1 OR jsonb_array_length(p_items) > 100 THEN
    RAISE EXCEPTION 'Invalid transaction items';
  END IF;

  v_name := NULLIF(btrim(p_contact_name), '');
  IF p_contact_id IS NOT NULL THEN
    SELECT * INTO v_contact FROM public.contacts WHERE id = p_contact_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'Invalid contact'; END IF;
    IF p_type = 'purchase' AND v_contact.type = 'customer' THEN RAISE EXCEPTION 'Invalid supplier'; END IF;
    IF p_type <> 'purchase' AND v_contact.type = 'supplier' THEN RAISE EXCEPTION 'Invalid customer'; END IF;
    v_name := v_contact.name;
  END IF;
  IF v_name IS NULL THEN
    v_name := CASE WHEN p_type = 'purchase' THEN 'Supplier' ELSE 'Walk-in Customer' END;
  END IF;

  FOR v_item IN SELECT value FROM jsonb_array_elements(p_items) AS entries(value) LOOP
    IF jsonb_typeof(v_item) <> 'object' OR (v_item->>'product_id') !~ '^[1-9][0-9]*$' THEN
      RAISE EXCEPTION 'Invalid product';
    END IF;
    v_product_id := (v_item->>'product_id')::bigint;
    SELECT * INTO v_product FROM public.products WHERE id = v_product_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Invalid product'; END IF;
    IF COALESCE(v_item->>'quantity', '') !~ '^[0-9]+(\.[0-9]+)?$' THEN RAISE EXCEPTION 'Invalid quantity'; END IF;
    v_quantity := (v_item->>'quantity')::numeric;
    IF v_quantity <= 0 THEN RAISE EXCEPTION 'Invalid quantity'; END IF;

    IF v_item ? 'unit_price' THEN
      IF COALESCE(v_item->>'unit_price', '') !~ '^[0-9]+(\.[0-9]+)?$' THEN RAISE EXCEPTION 'Invalid unit price'; END IF;
      v_unit_price := (v_item->>'unit_price')::numeric;
    ELSE
      v_unit_price := CASE WHEN p_type = 'purchase' THEN v_product.cost ELSE v_product.price END;
    END IF;
    IF v_unit_price < 0 THEN RAISE EXCEPTION 'Invalid unit price'; END IF;

    IF p_type <> 'purchase' THEN
      IF v_product.stock < (
        SELECT COALESCE(SUM((entry->>'quantity')::numeric), 0)
        FROM jsonb_array_elements(p_items) AS all_entries(entry)
        WHERE entry->>'product_id' = v_product_id::text
      ) THEN
        RAISE EXCEPTION 'Insufficient stock for %', v_product.name;
      END IF;
    END IF;

    v_net := round(v_quantity * v_unit_price, 2);
    v_line_tax := round(v_net * v_product.tax_rate / 100, 2);
    v_subtotal := v_subtotal + v_net;
    v_tax := v_tax + v_line_tax;
  END LOOP;

  INSERT INTO public.transactions (number, type, contact_id, contact_name, subtotal, tax, total, payment_method)
  VALUES (p_number, p_type, p_contact_id, v_name, v_subtotal, v_tax, v_subtotal + v_tax, COALESCE(NULLIF(btrim(p_payment_method), ''), 'Cash'))
  RETURNING * INTO v_transaction;

  FOR v_item IN SELECT value FROM jsonb_array_elements(p_items) AS entries(value) LOOP
    v_product_id := (v_item->>'product_id')::bigint;
    SELECT * INTO v_product FROM public.products WHERE id = v_product_id;
    v_quantity := (v_item->>'quantity')::numeric;
    v_unit_price := CASE
      WHEN v_item ? 'unit_price' THEN (v_item->>'unit_price')::numeric
      WHEN p_type = 'purchase' THEN v_product.cost
      ELSE v_product.price
    END;
    v_net := round(v_quantity * v_unit_price, 2);
    v_line_tax := round(v_net * v_product.tax_rate / 100, 2);

    INSERT INTO public.transaction_items (transaction_id, product_id, product_name, quantity, unit_price, tax_rate, line_total)
    VALUES (v_transaction.id, v_product.id, v_product.name, v_quantity, v_unit_price, v_product.tax_rate, v_net + v_line_tax);

    UPDATE public.products
    SET stock = CASE WHEN p_type = 'purchase' THEN stock + v_quantity ELSE stock - v_quantity END,
        cost = CASE WHEN p_type = 'purchase' THEN v_unit_price ELSE cost END
    WHERE id = v_product.id;
  END LOOP;

  RETURN v_transaction;
END;
$$;

REVOKE ALL ON FUNCTION public.create_erp_transaction(text, text, bigint, text, text, jsonb) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.create_erp_transaction(text, text, bigint, text, text, jsonb) TO service_role;

